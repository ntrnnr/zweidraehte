//! Focused project rendering used by non-interactive skeleton generation and
//! product-only editors. Existing projects are changed by replacing one
//! device declaration and inserting only newly referenced nets; unrelated
//! source, comments, and formatting remain byte-for-byte intact.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use thiserror::Error;
use zweidraehte_proto::address::{GroupAddress, IndividualAddress};

use super::{AuthoredLine, AuthoredProject};
use crate::{
    CouplerRoutingPolicy, DataSecureMode, DomainAddress, IpAssignment, IpDeviceConfiguration, IpLineConfiguration,
    IpServiceSecurity, Medium, MembershipRole, NetId, NetSecurityPolicy, ObjectFlagOverrides, ObjectPriority,
    ParamValue, ParameterAssignment, ProductReference, ProjectDeviceId, ProjectObjectConfiguration, RfDeviceMode,
};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DraftNet {
    pub id: NetId,
    pub address: GroupAddress,
    pub dpt: String,
    pub security: NetSecurityPolicy,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ProjectDeviceDraft {
    pub id: ProjectDeviceId,
    pub active: bool,
    /// Complete immutable package selector. A draft cannot name a package
    /// without also naming its exact `CatalogItem` leaf.
    pub product: ProductReference,
    pub address: IndividualAddress,
    /// Medium of the authored line which contains this device.
    pub medium: Medium,
    /// RF domain or KNX/IP routing multicast address shared by the line.
    pub domain: Option<DomainAddress>,
    /// Shared KNX/IP project identifier and secure-routing timing values.
    pub ip_line: Option<IpLineConfiguration>,
    /// RF Medium Object PID 51 value for this device, when required by its
    /// programming profile.
    pub rf_mode: Option<RfDeviceMode>,
    pub ip: Option<IpDeviceConfiguration>,
    pub routing: Option<CouplerRoutingPolicy>,
    pub serial: Option<[u8; 6]>,
    pub max_apdu: Option<u16>,
    pub data_secure: DataSecureMode,
    pub parameters: Vec<ParameterAssignment>,
    pub objects: BTreeMap<u16, ProjectObjectConfiguration>,
    pub nets: BTreeMap<NetId, DraftNet>,
}

#[derive(Debug, Error)]
pub enum RenderError {
    #[error("the project has no device `{0}`")]
    UnknownDevice(ProjectDeviceId),
    #[error("the project already has device `{0}`")]
    DuplicateDevice(ProjectDeviceId),
    #[error("device `{device}` cannot move outside its enclosing area/line through a local edit")]
    TopologyMove { device: ProjectDeviceId },
    #[error("net identifier `{0}` conflicts with an existing net")]
    NetConflict(NetId),
    #[error("the project has no net `{0}`")]
    UnknownNet(NetId),
    #[error("a group-address name cannot be empty")]
    EmptyNetName,
    #[error("area {area}, line {line} uses {existing:?}, not {requested:?}")]
    MediumConflict { area: u8, line: u8, existing: Medium, requested: Medium },
    #[error("area {area}, line {line} uses domain {existing:?}, not {requested:?}")]
    DomainConflict { area: u8, line: u8, existing: Option<DomainAddress>, requested: Option<DomainAddress> },
    #[error("{medium:?} requires a {expected} domain address")]
    InvalidDomain { medium: Medium, expected: &'static str },
    #[error("{medium:?} cannot declare a domain address")]
    UnexpectedDomain { medium: Medium },
    #[error("the all-zero and all-FF RF domain addresses are not commissioned domains")]
    InvalidRfDomain,
    #[error("the KNX/IP domain address is not multicast")]
    InvalidIpDomain,
    #[error("{medium:?} has incomplete or unexpected IP installation values")]
    InvalidIpLine { medium: Medium },
    #[error("{medium:?} cannot declare `rf_mode`")]
    UnexpectedRfMode { medium: Medium },
    #[error("address-zero topology coupler {address} requires an explicit `routing` policy")]
    MissingRouting { address: IndividualAddress },
    #[error("ordinary device {address} cannot declare a coupler `routing` policy")]
    UnexpectedRouting { address: IndividualAddress },
    #[error("the authored topology contains more than one area {area} or line {line}")]
    AmbiguousTopology { area: u8, line: u8 },
    #[error("the package selector's CatalogItem ID cannot be empty")]
    EmptyCatalogItem,
    #[error("the project language cannot be empty")]
    EmptyLanguage,
}

/// Render a complete minimal one-device project.
pub fn render_single_device_project(draft: &ProjectDeviceDraft) -> Result<String, RenderError> {
    validate_product_reference(&draft.product)?;
    validate_topology_draft(draft)?;

    let mut output = String::from("# KNX project generated by zweidraehte\n\n");
    render_nets(&mut output, draft.nets.values());
    writeln!(output, "area {} project {{", draft.address.area()).expect("String writes cannot fail");
    writeln!(output, "    line {} main {{", draft.address.line()).expect("String writes cannot fail");
    render_line_configuration(&mut output, "        ", draft);
    output.push_str(&render_device(draft, 8));
    output.push_str("    }\n}\n");
    Ok(output)
}

impl AuthoredProject {
    /// Change only the project-wide presentation language.
    pub fn render_language_update(&self, language: Option<&str>) -> Result<String, RenderError> {
        if language.is_some_and(str::is_empty) {
            return Err(RenderError::EmptyLanguage);
        }
        if self.language.as_deref() == language {
            return Ok(self.source.clone());
        }

        let mut source = self.source.clone();
        match (self.language_value_span, self.language_decl_span, language) {
            (Some(value_span), Some(_), Some(language)) => {
                source.replace_range(value_span.start..value_span.end, &quote(language));
            }
            (_, Some(declaration_span), None) => remove_declaration(&mut source, declaration_span),
            (None, None, Some(language)) => source.insert_str(0, &format!("language {}\n\n", quote(language))),
            _ => unreachable!("language value and declaration spans are recorded together"),
        }
        Ok(source)
    }

    /// Change only a device's recorded physical serial number.
    ///
    /// Commissioning learns this value from the live device, so updating it
    /// must not re-render unrelated parameters, comments, or object links.
    /// Existing values are replaced in place; a newly learned value is
    /// inserted beside the mandatory individual-address declaration.
    pub fn render_device_serial_update(
        &self,
        id: &ProjectDeviceId,
        serial: Option<[u8; 6]>,
    ) -> Result<String, RenderError> {
        let device = self.devices.get(id).ok_or_else(|| RenderError::UnknownDevice(id.clone()))?;
        if device.serial == serial {
            return Ok(self.source.clone());
        }

        let mut source = self.source.clone();
        match (device.serial_value_span, device.serial_decl_span, serial) {
            (Some(value_span), Some(_), Some(serial)) => {
                source.replace_range(value_span.start..value_span.end, &quote(&crate::format_serial(&serial)));
            }
            (_, Some(declaration_span), None) => {
                remove_declaration(&mut source, declaration_span);
            }
            (None, None, Some(serial)) => {
                insert_declaration_after(
                    &mut source,
                    device.address_decl_span,
                    &format!("serial {}", quote(&crate::format_serial(&serial))),
                );
            }
            _ => unreachable!("serial value and declaration spans are recorded together"),
        }

        Ok(source)
    }

    /// Change a net's human-readable name without changing its stable ID.
    ///
    /// Net IDs are referenced by memberships, keys and mutable deployment
    /// state. A presentation rename must therefore edit only this label. When
    /// the declaration already has a name, only its quoted token is replaced;
    /// adding the first name uses the security declaration as a local anchor
    /// and preserves every other authored byte.
    pub fn render_net_name_update(&self, id: &NetId, name: &str) -> Result<String, RenderError> {
        let name = name.trim();
        if name.is_empty() {
            return Err(RenderError::EmptyNetName);
        }
        let net = self.nets.get(id).ok_or_else(|| RenderError::UnknownNet(id.clone()))?;
        let quoted = quote(name);
        let mut source = self.source.clone();
        if let Some(span) = net.name_span {
            source.replace_range(span.start..span.end, &quoted);
            return Ok(source);
        }

        let at = net.security_decl_span.start;
        let line_start = source[..at].rfind('\n').map_or(0, |newline| newline + 1);
        let prefix = &source[line_start..at];
        let insertion = if prefix.chars().all(|character| matches!(character, ' ' | '\t')) {
            format!("name {quoted}\n{prefix}")
        } else {
            format!("name {quoted} ")
        };
        source.insert_str(at, &insertion);
        Ok(source)
    }

    /// Add a device while preserving every existing authored byte.
    ///
    /// The new declaration is placed in an existing matching line when one
    /// exists; otherwise the smallest missing topology wrapper is appended.
    /// This keeps imports local without teaching frontends how to splice Pest
    /// source spans themselves.
    pub fn render_device_add(&self, draft: &ProjectDeviceDraft) -> Result<String, RenderError> {
        if self.devices.contains_key(&draft.id) {
            return Err(RenderError::DuplicateDevice(draft.id.clone()));
        }
        validate_draft(self, draft)?;

        let area_number = draft.address.area();
        let line_number = draft.address.line();
        let matching_areas: Vec<_> = self.areas.iter().filter(|area| area.number == area_number).collect();
        if matching_areas.len() > 1 {
            return Err(RenderError::AmbiguousTopology { area: area_number, line: line_number });
        }

        let mut source = self.source.clone();
        if let Some(area) = matching_areas.first() {
            let matching_lines: Vec<_> = area.lines.iter().filter(|line| line.number == line_number).collect();
            if matching_lines.len() > 1 {
                return Err(RenderError::AmbiguousTopology { area: area_number, line: line_number });
            }
            if let Some(line) = matching_lines.first() {
                ensure_line_matches(line, area_number, draft)?;

                let at = closing_line_start(&source, line.span);
                source.insert_str(at, &format!("\n{}", render_device(draft, 8)));
            } else {
                let at = closing_line_start(&source, area.span);
                source.insert_str(at, &render_line(draft));
            }
        } else {
            append_block(&mut source, &render_area(draft));
        }
        insert_new_nets(self, draft, &mut source);
        Ok(source)
    }

    /// Return source with one device configuration replaced and newly used
    /// nets inserted before the first area. No file is written here.
    pub fn render_device_update(&self, draft: &ProjectDeviceDraft) -> Result<String, RenderError> {
        let current = self.devices.get(&draft.id).ok_or_else(|| RenderError::UnknownDevice(draft.id.clone()))?;
        if current.area != draft.address.area() || current.line != draft.address.line() {
            return Err(RenderError::TopologyMove { device: draft.id.clone() });
        }
        validate_draft(self, draft)?;

        let line = self
            .areas
            .iter()
            .filter(|area| area.number == current.area)
            .flat_map(|area| area.lines.iter())
            .filter(|line| line.number == current.line)
            .collect::<Vec<_>>();
        if line.len() != 1 {
            return Err(RenderError::AmbiguousTopology { area: current.area, line: current.line });
        }
        ensure_line_matches(line[0], current.area, draft)?;

        // Locate the enclosing top-level declarations before replacing the
        // device. Device spans refer to the authored source, while rendering a
        // changed device may alter every byte offset after its start.
        let area_start = self.areas.iter().map(|area| area.span.start).min().unwrap_or(self.source.len());

        // Pest's device span begins at the `device` keyword, after silent
        // whitespace has already been consumed. Replacing that span with a
        // string that also carries indentation leaves the old prefix behind,
        // shifting the declaration right on every save. Own the whole prefix
        // when the declaration starts on its own line and derive its canonical
        // child indentation from the enclosing area/line. Besides making saves
        // idempotent, this pulls files affected by the old bug back into place.
        let (device_span, rendered_device) = self.device_replacement(current, draft);
        let mut replacements = vec![(device_span, rendered_device.trim_end().to_string())];
        for (id, net) in &draft.nets {
            if let Some(existing) = self.nets.get(id)
                && existing.security != net.security
            {
                replacements.push((existing.security_span, policy_name(net.security).to_string()));
            }
        }
        let area_shift: isize = replacements
            .iter()
            .filter(|(span, _)| span.end <= area_start)
            .map(|(span, replacement)| replacement.len() as isize - (span.end - span.start) as isize)
            .sum();
        replacements.sort_by_key(|(span, _)| std::cmp::Reverse(span.start));
        let mut source = self.source.clone();
        for (span, replacement) in replacements {
            source.replace_range(span.start..span.end, &replacement);
        }
        let new_ids: BTreeSet<_> = draft.nets.keys().filter(|id| !self.nets.contains_key(*id)).cloned().collect();
        if !new_ids.is_empty() {
            let mut added = String::new();
            render_nets(&mut added, new_ids.iter().map(|id| &draft.nets[id]));
            let adjusted_area = usize::try_from(area_start as isize + area_shift).expect("area remains in source");
            source.insert_str(adjusted_area, &added);
        }
        Ok(source)
    }

    fn device_replacement(
        &self,
        current: &crate::ProjectDevice,
        draft: &ProjectDeviceDraft,
    ) -> (crate::SourceSpan, String) {
        let Some((device_line_start, _)) = declaration_indent(&self.source, current.span) else {
            // Compact one-line projects have non-whitespace before `device`.
            // Its separator remains outside the span, so the replacement must
            // begin directly with the keyword.
            return (current.span, render_device_with_prefix(draft, ""));
        };

        let enclosing = self.areas.iter().find_map(|area| {
            (area.span.start <= current.span.start && current.span.end <= area.span.end).then(|| {
                area.lines
                    .iter()
                    .find(|line| line.span.start <= current.span.start && current.span.end <= line.span.end)
                    .map(|line| (area, line))
            })?
        });
        let prefix = enclosing
            .and_then(|(area, line)| {
                let (_, area_indent) = declaration_indent(&self.source, area.span)?;
                let (_, line_indent) = declaration_indent(&self.source, line.span)?;
                let indent_step =
                    line_indent.strip_prefix(area_indent).filter(|step| !step.is_empty()).unwrap_or("    ");
                Some(format!("{line_indent}{indent_step}"))
            })
            .unwrap_or_else(|| "        ".to_string());
        (
            crate::SourceSpan { start: device_line_start, end: current.span.end },
            render_device_with_prefix(draft, &prefix),
        )
    }
}

fn validate_draft(project: &AuthoredProject, draft: &ProjectDeviceDraft) -> Result<(), RenderError> {
    validate_product_reference(&draft.product)?;
    validate_topology_draft(draft)?;

    for (id, net) in &draft.nets {
        if let Some(existing) = project.nets.get(id)
            && (existing.address != net.address || existing.dpt != net.dpt)
        {
            return Err(RenderError::NetConflict(id.clone()));
        }
    }
    Ok(())
}

fn validate_product_reference(product: &ProductReference) -> Result<(), RenderError> {
    let ProductReference::Package { catalog_item, .. } = product;
    if catalog_item.is_empty() {
        return Err(RenderError::EmptyCatalogItem);
    }
    Ok(())
}

fn validate_topology_draft(draft: &ProjectDeviceDraft) -> Result<(), RenderError> {
    match (draft.medium, draft.domain) {
        (Medium::Rf, Some(DomainAddress::Rf(domain))) if domain != [0; 6] && domain != [0xff; 6] => {}
        (Medium::Rf, Some(DomainAddress::Rf(_))) => return Err(RenderError::InvalidRfDomain),
        (Medium::Rf, None) => return Err(RenderError::InvalidDomain { medium: draft.medium, expected: "6-byte RF" }),
        (Medium::Ip, Some(DomainAddress::Ip(address))) if address[0] & 0xf0 == 0xe0 => {}
        (Medium::Ip, Some(DomainAddress::Ip(_))) => return Err(RenderError::InvalidIpDomain),
        (Medium::Ip, None) => {
            return Err(RenderError::InvalidDomain { medium: draft.medium, expected: "IPv4 multicast" });
        }
        (Medium::Tp1, None) => {}
        (Medium::Tp1, Some(_))
        | (Medium::Rf, Some(DomainAddress::Ip(_)))
        | (Medium::Ip, Some(DomainAddress::Rf(_))) => {
            return Err(RenderError::UnexpectedDomain { medium: draft.medium });
        }
    }

    match (draft.medium, draft.ip_line.as_ref(), draft.ip.as_ref()) {
        (Medium::Ip, Some(line), Some(device)) => {
            if let Some(security) = &device.security
                && (line.multicast_latency_tolerance_ms != Some(security.multicast_latency_tolerance_ms)
                    || line.sync_latency_fraction != Some(security.sync_latency_fraction))
            {
                return Err(RenderError::InvalidIpLine { medium: draft.medium });
            }
        }
        (Medium::Ip, Some(_), None) => {}
        (Medium::Ip, _, _) | (_, Some(_), _) | (_, _, Some(_)) => {
            return Err(RenderError::InvalidIpLine { medium: draft.medium });
        }
        _ => {}
    }

    match (draft.medium, draft.rf_mode) {
        (Medium::Rf, _) | (Medium::Tp1 | Medium::Ip, None) => {}
        (_, Some(_)) => return Err(RenderError::UnexpectedRfMode { medium: draft.medium }),
    }

    match (draft.address.device() == 0, draft.routing) {
        (true, None) => return Err(RenderError::MissingRouting { address: draft.address }),
        (false, Some(_)) => return Err(RenderError::UnexpectedRouting { address: draft.address }),
        _ => {}
    }

    Ok(())
}

fn ensure_line_matches(line: &AuthoredLine, area: u8, draft: &ProjectDeviceDraft) -> Result<(), RenderError> {
    if line.medium != draft.medium {
        return Err(RenderError::MediumConflict {
            area,
            line: line.number,
            existing: line.medium,
            requested: draft.medium,
        });
    }
    if line.domain != draft.domain {
        return Err(RenderError::DomainConflict {
            area,
            line: line.number,
            existing: line.domain,
            requested: draft.domain,
        });
    }
    if line.ip != draft.ip_line {
        return Err(RenderError::InvalidIpLine { medium: draft.medium });
    }
    Ok(())
}

fn insert_new_nets(project: &AuthoredProject, draft: &ProjectDeviceDraft, source: &mut String) {
    let new_ids: BTreeSet<_> = draft.nets.keys().filter(|id| !project.nets.contains_key(*id)).cloned().collect();
    if new_ids.is_empty() {
        return;
    }
    let mut added = String::new();
    render_nets(&mut added, new_ids.iter().map(|id| &draft.nets[id]));
    let at = project.areas.iter().map(|area| area.span.start).min().unwrap_or(0);
    source.insert_str(at, &added);
}

fn closing_line_start(source: &str, span: crate::SourceSpan) -> usize {
    let closing_brace = span.end.saturating_sub(1);
    source[..closing_brace].rfind('\n').map_or(closing_brace, |newline| newline + 1)
}

/// Return the declaration's line start and indentation when no syntax
/// precedes the declaration on that line.
fn declaration_indent(source: &str, span: crate::SourceSpan) -> Option<(usize, &str)> {
    let start = span.start.min(source.len());
    let line_start = source[..start].rfind('\n').map_or(0, |newline| newline + 1);
    let prefix = &source[line_start..start];
    prefix.chars().all(|character| matches!(character, ' ' | '\t')).then_some((line_start, prefix))
}

fn insert_declaration_after(source: &mut String, anchor: crate::SourceSpan, declaration: &str) {
    let line_start = source[..anchor.start].rfind('\n').map_or(0, |newline| newline + 1);
    let prefix = &source[line_start..anchor.start];
    let line_end = source[anchor.end..].find('\n').map(|offset| anchor.end + offset);

    if prefix.chars().all(|character| matches!(character, ' ' | '\t')) {
        let insertion = format!("{prefix}{declaration}\n");
        match line_end {
            Some(line_end) => source.insert_str(line_end + 1, &insertion),
            None => source.push_str(&format!("\n{insertion}")),
        }
    } else {
        source.insert_str(anchor.end, &format!(" {declaration}"));
    }
}

fn remove_declaration(source: &mut String, declaration: crate::SourceSpan) {
    let line_start = source[..declaration.start].rfind('\n').map_or(0, |newline| newline + 1);
    let line_end = source[declaration.end..].find('\n').map_or(source.len(), |offset| declaration.end + offset);
    let prefix = &source[line_start..declaration.start];
    let suffix = &source[declaration.end..line_end];

    if prefix.chars().all(|character| matches!(character, ' ' | '\t')) && suffix.trim().is_empty() {
        let end = if line_end < source.len() { line_end + 1 } else { line_end };
        source.replace_range(line_start..end, "");
    } else {
        source.replace_range(declaration.start..declaration.end, "");
    }
}

fn append_block(source: &mut String, block: &str) {
    if !source.is_empty() && !source.ends_with('\n') {
        source.push('\n');
    }
    if !source.is_empty() && !source.ends_with("\n\n") {
        source.push('\n');
    }
    source.push_str(block);
}

fn render_area(draft: &ProjectDeviceDraft) -> String {
    let mut output = String::new();
    writeln!(output, "area {} project {{", draft.address.area()).expect("String writes cannot fail");
    output.push_str(&render_line(draft));
    output.push_str("}\n");
    output
}

fn render_line(draft: &ProjectDeviceDraft) -> String {
    let mut output = String::new();
    writeln!(output, "    line {} main {{", draft.address.line()).expect("String writes cannot fail");
    render_line_configuration(&mut output, "        ", draft);
    output.push_str(&render_device(draft, 8));
    output.push_str("    }\n");
    output
}

fn render_line_configuration(output: &mut String, prefix: &str, draft: &ProjectDeviceDraft) {
    writeln!(output, "{prefix}medium {}", medium_name(draft.medium)).expect("String writes cannot fail");
    if let Some(domain) = draft.domain {
        writeln!(output, "{prefix}domain \"{domain}\"").expect("String writes cannot fail");
    }
    if let Some(ip) = draft.ip_line {
        writeln!(output, "{prefix}project_installation_id {}", ip.project_installation_id)
            .expect("String writes cannot fail");
        if let Some(value) = ip.multicast_latency_tolerance_ms {
            writeln!(output, "{prefix}multicast_latency_tolerance {value}").expect("String writes cannot fail");
        }
        if let Some(value) = ip.sync_latency_fraction {
            writeln!(output, "{prefix}sync_latency_fraction {value}").expect("String writes cannot fail");
        }
    }
    output.push('\n');
}

fn render_nets<'a>(output: &mut String, nets: impl IntoIterator<Item = &'a DraftNet>) {
    let nets: Vec<_> = nets.into_iter().collect();
    for net in &nets {
        writeln!(output, "ga {} = {}", net.id, net.address).expect("String writes cannot fail");
    }
    if !nets.is_empty() {
        output.push('\n');
    }
    for net in &nets {
        writeln!(output, "net {} : {} {{ security {} }}", net.id, net.dpt, policy_name(net.security))
            .expect("String writes cannot fail");
    }
    if !nets.is_empty() {
        output.push('\n');
    }
}

fn render_device(draft: &ProjectDeviceDraft, indent: usize) -> String {
    render_device_with_prefix(draft, &" ".repeat(indent))
}

fn render_device_with_prefix(draft: &ProjectDeviceDraft, prefix: &str) -> String {
    let nested = format!("{prefix}    ");
    let mut output = String::new();
    writeln!(output, "{prefix}device {} {{", draft.id).expect("String writes cannot fail");
    if !draft.active {
        writeln!(output, "{nested}active false").expect("String writes cannot fail");
    }
    let ProductReference::Package { package, catalog_item } = &draft.product;
    writeln!(output, "{nested}product package:{}", quote(&package.to_string())).expect("String writes cannot fail");
    writeln!(output, "{nested}catalog_item {}", quote(catalog_item)).expect("String writes cannot fail");
    writeln!(output, "{nested}address {}", draft.address).expect("String writes cannot fail");
    if let Some(mode) = draft.rf_mode {
        writeln!(output, "{nested}rf_mode {}", rf_mode_name(mode)).expect("String writes cannot fail");
    }
    if let Some(ip) = &draft.ip {
        match ip.assignment {
            IpAssignment::AutomaticDhcp => {
                writeln!(output, "{nested}ip_assignment dhcp").expect("String writes cannot fail");
            }
            IpAssignment::Fixed { address, subnet_mask, default_gateway } => {
                writeln!(output, "{nested}ip_assignment fixed").expect("String writes cannot fail");
                writeln!(output, "{nested}ip_address \"{}\"", ipv4(address)).expect("String writes cannot fail");
                writeln!(output, "{nested}subnet_mask \"{}\"", ipv4(subnet_mask)).expect("String writes cannot fail");
                writeln!(output, "{nested}default_gateway \"{}\"", ipv4(default_gateway))
                    .expect("String writes cannot fail");
            }
        }
        writeln!(output, "{nested}multicast_ttl {}", ip.multicast_ttl).expect("String writes cannot fail");
        writeln!(output, "{nested}friendly_name {}", quote(&ip.friendly_name)).expect("String writes cannot fail");
        for address in &ip.additional_individual_addresses {
            writeln!(output, "{nested}additional_address {address}").expect("String writes cannot fail");
        }
        if let Some(security) = &ip.security {
            writeln!(output, "{nested}ip_routing {}", ip_security_name(security.routing))
                .expect("String writes cannot fail");
            writeln!(output, "{nested}ip_device_management {}", ip_security_name(security.device_management))
                .expect("String writes cannot fail");
            writeln!(output, "{nested}ip_tunnelling {}", ip_security_name(security.tunnelling))
                .expect("String writes cannot fail");
            for user in &ip.password_users {
                writeln!(output, "{nested}ip_password_user {user}").expect("String writes cannot fail");
            }
            for binding in &security.tunnelling_users {
                writeln!(output, "{nested}ip_tunnelling_user {} {}", binding.user_id, binding.address_index)
                    .expect("String writes cannot fail");
            }
        }
    }
    if let Some(routing) = draft.routing {
        writeln!(output, "{nested}routing {}", routing_name(routing)).expect("String writes cannot fail");
    }
    if let Some(serial) = draft.serial {
        writeln!(output, "{nested}serial \"{}\"", crate::format_serial(&serial)).expect("String writes cannot fail");
    }
    if let Some(max_apdu) = draft.max_apdu {
        writeln!(output, "{nested}max_apdu {max_apdu}").expect("String writes cannot fail");
    }
    writeln!(output, "{nested}data_secure {}", if draft.data_secure.is_enabled() { "enabled" } else { "disabled" })
        .expect("String writes cannot fail");
    for parameter in &draft.parameters {
        writeln!(output, "{nested}param {} = {}", quote(&parameter.id), render_value(&parameter.value))
            .expect("String writes cannot fail");
    }
    for object in draft.objects.values() {
        writeln!(output, "\n{nested}object {} {{", object.com_object).expect("String writes cannot fail");
        for membership in &object.memberships {
            let keyword = if membership.role == MembershipRole::Primary { "on" } else { "also on" };
            writeln!(output, "{nested}    {keyword} {}", membership.net).expect("String writes cannot fail");
        }
        if object.flags != ObjectFlagOverrides::default() {
            writeln!(output, "\n{nested}    flags {{").expect("String writes cannot fail");
            render_flags(&mut output, &nested, object.flags);
            writeln!(output, "{nested}    }}").expect("String writes cannot fail");
        }
        writeln!(output, "{nested}}}").expect("String writes cannot fail");
    }
    writeln!(output, "{prefix}}}").expect("String writes cannot fail");
    output
}

fn render_flags(output: &mut String, prefix: &str, flags: ObjectFlagOverrides) {
    let entries = [
        ("communication", flags.communication),
        ("read", flags.read),
        ("write", flags.write),
        ("transmit", flags.transmit),
        ("update", flags.update),
        ("read_on_init", flags.read_on_init),
    ];
    for (name, value) in entries {
        if let Some(value) = value {
            writeln!(output, "{prefix}        {name} {value}").expect("String writes cannot fail");
        }
    }
    if let Some(priority) = flags.priority {
        writeln!(output, "{prefix}        priority {}", priority_name(priority)).expect("String writes cannot fail");
    }
}

fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

fn render_value(value: &ParamValue) -> String {
    match value {
        ParamValue::Integer(value) => value.to_string(),
        ParamValue::Float(value) => value.to_string(),
        ParamValue::Text(value) => quote(value),
    }
}

fn policy_name(policy: NetSecurityPolicy) -> &'static str {
    match policy {
        NetSecurityPolicy::Plain => "plain",
        NetSecurityPolicy::Automatic => "automatic",
        NetSecurityPolicy::Authentication => "authentication",
        NetSecurityPolicy::AuthenticationConfidentiality => "authentication_confidentiality",
    }
}

fn medium_name(medium: Medium) -> &'static str {
    match medium {
        Medium::Tp1 => "tp1",
        Medium::Rf => "rf",
        Medium::Ip => "ip",
    }
}

fn rf_mode_name(mode: RfDeviceMode) -> &'static str {
    match mode {
        RfDeviceMode::Ready => "ready",
        RfDeviceMode::Multi => "multi",
    }
}

fn ip_security_name(mode: IpServiceSecurity) -> &'static str {
    match mode {
        IpServiceSecurity::Plain => "plain",
        IpServiceSecurity::Secure => "secure",
    }
}

fn ipv4(value: [u8; 4]) -> String {
    format!("{}.{}.{}.{}", value[0], value[1], value[2], value[3])
}

fn routing_name(policy: CouplerRoutingPolicy) -> &'static str {
    match policy {
        CouplerRoutingPolicy::Filter => "filter",
        CouplerRoutingPolicy::RouteAll => "route_all",
        CouplerRoutingPolicy::BlockAll => "block_all",
    }
}

fn priority_name(priority: ObjectPriority) -> &'static str {
    match priority {
        ObjectPriority::System => "system",
        ObjectPriority::High => "high",
        ObjectPriority::Alarm => "alarm",
        ObjectPriority::Low => "low",
    }
}

