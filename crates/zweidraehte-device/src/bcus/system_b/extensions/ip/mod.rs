// Plain KNX/IP has no Data Secure layer at this level — security on IP
// stacks is added by wrapping `IpExtensionState` in `SecureExtensionState`.
// The bare extension's `Plain` defaults are correct.
impl<const CAPS: u16> HasGoSecurityView for IpExtensionState<CAPS> {}

// The `ExtensionState` impl (Config / Resources / from_config / to_config) is
// generated by `#[derive(ExtensionState)]` on the struct above. `from_config`
// deliberately does *not* call `apply_current_config()`: the caller applies
// the IP config to the platform at the appropriate time — typically only when
// the assignment method is Manual/static. Applying during `from_config` would
// overwrite a DHCP lease acquired before state was loaded from flash (common
// on embedded platforms where DHCP runs during hardware init, before persisted
// state is deserialised). The derive's generated `from_config` only restores
// field values, matching that contract.
//
// `on_erase` is hand-written here (`on_erase = manual` on the derive routes the
// trait method to this `on_erase_manual`) because a factory reset must also
// rebind to the default multicast group via the same channel writes use —
// a side-effect outside the field-mapping.
impl<const CAPS: u16> IpExtensionState<CAPS> {
    fn on_erase_manual(&self, code: EraseCode) {
        if matches!(code, EraseCode::FactoryReset | EraseCode::FactoryResetKeepIA) {
            let defaults: IpExtensionConfig = IpExtensionConfig::default();
            self.friendly_name.set(defaults.friendly_name);
            self.friendly_name_len.set(defaults.friendly_name_len as usize);
            self.configured_ip.set(Ipv4Addr::from(defaults.configured_ip));
            self.configured_subnet.set(Ipv4Addr::from(defaults.configured_subnet));
            self.configured_gateway.set(Ipv4Addr::from(defaults.configured_gateway));
            self.ip_assignment_method.set(defaults.ip_assignment_method);
            let default_mcast = Ipv4Addr::from(defaults.routing_multicast);
            self.routing_multicast.set(default_mcast);
            // Factory reset must also rebind to the default group, via
            // the same path writes use.
            let _ = self.rebind_channel.try_send(default_mcast);
            self.ttl.set(defaults.ttl);
            self.project_installation_id.set(defaults.project_installation_id);
        }
    }
}

impl<const CAPS: u16> HasSecurityMode for IpExtensionState<CAPS> {}

impl<const CAPS: u16> HasRoutingMulticastRebind for IpExtensionState<CAPS> {
    fn routing_multicast_rebind_channel(&self) -> &RoutingMulticastRebindChannel {
        &self.rebind_channel
    }
}

