/// Persisted IP configuration (for KNX/IP devices).
///
/// All IP-specific settings that can be configured via ETS or
/// the IP Parameter Object. Implements [`ExtensionConfig`] so it
/// can be used as the `E` parameter of
/// [`DeviceConfig`](crate::bcus::system_b::DeviceConfig).
///
/// Tunnelling-only state (the additional individual address list)
/// lives on [`TunnellingExtensionConfig`](super::TunnellingExtensionConfig)
/// — paired with this config inside
/// [`IpInterfaceExtension`](super::IpInterfaceExtension) on
/// tunnelling-capable devices.
// `IpExtensionConfig` (the persisted mirror) is generated by
// `#[derive(ExtensionState)]` on `IpExtensionState` below. The struct's
// field set, serde derives, and `ExtensionConfig` impl come from the
// derive; only the non-trivial factory `Default` (DHCP method + standard
// `224.0.23.12` multicast group, which are *not* per-field defaults) and
// the address-decoding helpers stay hand-written here — hence
// `default = manual` on the derive.
impl Default for IpExtensionConfig {
    fn default() -> Self {
        Self {
            friendly_name: [0; 30],
            friendly_name_len: 0,
            configured_ip: [0, 0, 0, 0],
            configured_subnet: [255, 255, 255, 0],
            configured_gateway: [0, 0, 0, 0],
            ip_assignment_method: 0x04, // DHCP
            routing_multicast: [224, 0, 23, 12],
            ttl: 16,
            project_installation_id: 0,
        }
    }
}

impl IpExtensionConfig {
    /// Get the configured IP address as an `Ipv4Addr`.
    pub fn configured_ip_addr(&self) -> Ipv4Addr {
        Ipv4Addr::from(self.configured_ip)
    }

    /// Get the routing multicast address as an `Ipv4Addr`.
    pub fn routing_multicast_addr(&self) -> Ipv4Addr {
        Ipv4Addr::from(self.routing_multicast)
    }
}

// ============================================================================
// IP Assignment Result
