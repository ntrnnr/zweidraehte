pub type IpDeviceState<
    const ADT_SIZE: usize,
    const AST_SIZE: usize,
    const COT_SIZE: usize,
    D: StackDefinition,
    F: FeatureSet,
> = SystemBDeviceState<ADT_SIZE, AST_SIZE, COT_SIZE, D, IpExtensionFor<F>>;

