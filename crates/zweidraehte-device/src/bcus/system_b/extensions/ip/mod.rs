        self.routing_multicast.set(addr);
        // Notify the KNX/IP link-layer runtime so it can rejoin the
        // multicast group in time for MaC's 1 s retry window
        // (03/02/06 §4.3.5.3.5.1). Drop on a full channel is fine —
