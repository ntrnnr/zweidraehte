/// A block CRC did not match.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[cfg_attr(feature = "defmt", derive(defmt::Format))]
pub struct CrcError;

/// Payload bytes in the first block (the length byte plus 9 telegram bytes).
const FIRST_BLOCK: usize = 10;
/// Payload bytes in every block after the first.
const NEXT_BLOCK: usize = 16;

/// Standard MSB-first table CRC-16 (poly `0x3D65`, init `0x0000`) over `data`.
fn crc16(data: &[u8]) -> u16 {
    let mut crc = 0u16;
    for &b in data {
        let idx = (((crc >> 8) as u8) ^ b) as usize;
        crc = (crc << 8) ^ ((CRC_TABLE1[idx] as u16) << 8) ^ (CRC_TABLE2[idx] as u16);
    }
    crc
}

/// The 16-bit frame-check sequence transmitted for a block: the one's
/// complement of the block CRC (KNX 03/02/05 §6.1.2.4). Transmitted MSB-first,
/// i.e. big-endian, by the callers below.
pub fn block_fcs(block: &[u8]) -> u16 {
    !crc16(block)
}

/// Telegram payload byte count for a frame whose length field is `len`.
fn payload_len(len: u8) -> usize {
    len as usize + 1
}

/// Split a telegram (`telegram[0]` is the length field) into CRC-protected
/// blocks, writing the on-air byte stream (telegram bytes with a 2-byte FCS
/// after each block) into `dst` and returning its length.
///
/// `dst` must be at least [`crate::frame::MAX_ONAIR_LEN`] bytes.
pub fn insert_block_crcs(telegram: &[u8], dst: &mut [u8]) -> usize {
    let want = payload_len(telegram[0]).min(telegram.len());
    let mut src = 0usize;
    let mut out = 0usize;
    let mut block = FIRST_BLOCK;
    while src < want {
        let n = block.min(want - src);
        dst[out..out + n].copy_from_slice(&telegram[src..src + n]);
        let fcs = block_fcs(&telegram[src..src + n]);
        dst[out + n] = (fcs >> 8) as u8; // MSB first
        dst[out + n + 1] = fcs as u8;
        src += n;
        out += n + 2;
        block = NEXT_BLOCK;
    }
    out
}

/// Verify the per-block CRCs of a Manchester-decoded on-air frame and copy the
/// stripped telegram (length byte first, FCS bytes removed) into `out`.
///
/// Returns the number of telegram bytes written, or [`CrcError`] on any block
/// CRC mismatch or if `onair` is too short for the frame its length field
/// declares.
pub fn verify_and_strip(onair: &[u8], out: &mut [u8]) -> Result<usize, CrcError> {
    if onair.is_empty() {
        return Err(CrcError);
    }
    let want = payload_len(onair[0]);
    if want > out.len() {
        return Err(CrcError);
    }

    let mut inp = 0usize;
    let mut written = 0usize;
    let mut block = FIRST_BLOCK;
    while written < want {
        let n = block.min(want - written);
        // Each block is `n` payload bytes followed by its 2-byte FCS.
        if inp + n + 2 > onair.len() {
            return Err(CrcError);
        }
        let payload = &onair[inp..inp + n];
        let received = ((onair[inp + n] as u16) << 8) | onair[inp + n + 1] as u16;
        if block_fcs(payload) != received {
            return Err(CrcError);
        }
        out[written..written + n].copy_from_slice(payload);
        written += n;
        inp += n + 2;
        block = NEXT_BLOCK;
    }
    Ok(written)
}
