//! KNX-RF block CRC-16.
//!
//! KNX-RF protects the telegram with a CRC-16 (polynomial `0x3D65`, the KNX-RF
//! "CRC2") inserted after each block: the first block carries 10 bytes
//! (including the length byte), every following block 16, and each is followed
//! by two CRC bytes. The SX1211 cannot do this in hardware (its packet engine
//! appends a single trailing CRC), so we compute it in software.
//!
//! # Definition (KNX 03/02/05 §6.1.2.4)
//!
//! The standard specifies the CRC "according to FT3 of IEC 870-5-1": generator
//! polynomial `0x3D65`, started at zero, data treated MSB-first, and the CRC
//! result **complemented**, with the MSB of the 16-bit CRC transmitted first.
//! The standard's worked example — the sequence `01 02 03 04 05 06 07 08` has
//! CRC `0xFCBC` — is checked in `tests/crc_roundtrip.rs`.
//!
//! # Implementation
//!
//! We use two CRC lookup tables — the standard MSB-first byte tables for
//! polynomial `0x3D65` (e.g. `TABLE[1] = 0x3D65`) — and drive them per the
//! standard above:
//! init `0x0000`, complement the result, transmit big-endian. We split into
//! the standard 10/16-byte blocks, append each block's 2-octet FCS, and verify
//! by recomputing. [`insert_block_crcs`] and [`verify_and_strip`] are exact
//! inverses, pinned down by the round-trip and known-answer tests.

