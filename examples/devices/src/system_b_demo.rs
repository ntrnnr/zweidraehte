/// Channel output mode - controls which DPT the output comm object uses.
///
/// This enum is used as a selector for ComObjectRefs. In ETS, when the user
/// changes the channel mode parameter, the comm object's DPT changes accordingly:
/// - Switch mode: DPT_Switch (1 bit)
/// - Dimmer mode: DPT_Value_1_Ucount (8 bit, 0-255)
/// - Blind mode: DPT_Value_1_Ucount (8 bit, 0-100% position)
#[derive(Debug, Clone, Copy, PartialEq, Eq, EtsEnum, Serialize, Deserialize)]
#[repr(u8)]
pub enum ChannelMode {
    /// Disabled - no output
    #[ets(display = "Disabled")]
    Disabled = 0,

    /// Switch mode - on/off control
    #[ets(display = "Switch")]
    Switch = 1,

    /// Dimmer mode - 0-100% brightness
    #[ets(display = "Dimmer")]
    Dimmer = 2,

    /// Blind/shutter mode - position control
    #[ets(display = "Blind")]
    Blind = 3,
}

impl ConstDefault for ChannelMode {
    const DEFAULT: Self = Self::Disabled;
}

