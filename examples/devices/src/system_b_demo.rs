/// Demo union for testing ETS union export.
///
/// The `#[ets_union]` macro generates:
/// - `ETS_UNION_INFO`: Union metadata including variant parameters
/// - `ETS_SELECTOR_VARIANTS`: Enum variants for the discriminant/selector
