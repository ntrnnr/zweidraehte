/// Application parameters for the demo device.
///
/// The `#[ets_params]` macro generates:
/// - `ETS_PARAMS`: Basic parameter definitions
/// - `ETS_PARAMS_EXT`: Extended definitions with enum variants
/// - `MODE_VARIANTS`: Auto-generated const for enum variants (named after the field)
/// - `ETS_UNIONS`: Union field information for union parameters
///
/// ## ComObjectRef Integration
///
/// The `channel_a_config` and `channel_b_config` union parameters control which
/// ComObjectRef is active for each channel. The union selector (e.g. "Switch Mode")
/// determines which variant-specific parameters are shown, AND which comm object
/// DPT is active.
///
/// Union fields can be placed anywhere in the struct. The macro uses `core::mem::offset_of!`
/// to correctly calculate field offsets regardless of union placement.
#[ets_params]
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub struct DemoParams {
    /// Channel A output configuration - controls comm object DPT and mode-specific params
    #[ets(union, display = "Channel A Config")]
    pub channel_a_config: OutputConfig,

    /// Channel B output configuration
    #[ets(union, display = "Channel B Config")]
    pub channel_b_config: OutputConfig,

    /// Input source configuration
    #[ets(union, display = "Input Source")]
    pub input_source: InputSource,

    /// Scene configuration
    #[ets(union, display = "Scene Config")]
    pub scene_config: SceneConfig,

    /// Send cycle time in seconds (0 = disabled)
    #[ets(display = "Send Cycle Time", enum_variants("Disabled" => 0, "10s" => 10, "30s" => 30, "60s" => 60, "300s" => 300))]
    pub send_cycle_time: BeU16,

    /// Lock behavior with enum variants
    #[ets(display = "Lock Behavior", enum_variants("No Action" => 0, "Lock Off" => 1, "Lock On" => 2, "Lock Toggle" => 3))]
    pub lock_behavior: u8,

    /// Gate for the Diagnostics channel tab: the whole tab only exists
    /// while this is "Shown" (a choose directly under Dynamic — the
    /// ETS6 idiom for channels enabled by a parameter).
    #[ets(display = "Diagnostics page", enum_variants("Hidden" => 0, "Shown" => 1))]
    pub show_diagnostics: u8,

    /// Heartbeat supervision interval, shown on the gated Diagnostics tab
    #[ets(display = "Heartbeat Interval", enum_variants("30s" => 0, "60s" => 1, "300s" => 2))]
    pub heartbeat_interval: u8,
}

